export const orderUnitProblemsByDifficulty = (
  unitId: string,
  problemIds: readonly string[],
): string[] => {
  const ordered = UNIT_PROBLEM_READING_ORDER[unitId] ?? [];
  const members = new Set(problemIds);
  if (
    members.size !== problemIds.length ||
    new Set(ordered).size !== ordered.length ||
    ordered.length !== problemIds.length ||
    ordered.some((id) => !members.has(id))
  ) {
    throw new Error(`UNIT_PROBLEM_READING_ORDER_INCOMPLETE:${unitId}`);
  }
  return [...ordered];
};
